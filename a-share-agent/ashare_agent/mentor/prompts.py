def profile_block(profile: dict, rules: list[str]) -> str:
    lines = ["【用户画像】"]
    labels = {
        "capital_range": "资金规模", "experience_years": "炒股年限", "max_drawdown": "能承受的最大回撤",
        "holding_period": "常用持股周期", "can_watch": "盘中能否看盘", "t_experience": "做T经验",
        "goal": "目标", "notes": "其他", "summary": "导师总结",
    }
    for k, label in labels.items():
        if profile.get(k):
            lines.append(f"- {label}：{profile[k]}")
    if profile.get("mistakes"):
        lines.append(f"- 自认常犯的错：{'、'.join(profile['mistakes'])}")
    if len(lines) == 1:
        lines.append("- （用户还没做访谈）")
    lines.append("【用户的硬规则】")
    lines += [f"- {r}" for r in rules]
    return "\n".join(lines)


def data_block(data: dict) -> str:
    return "数据（JSON，程序已算好的数字原样引用）：\n" + json.dumps(data, ensure_ascii=False, default=str, indent=1)


